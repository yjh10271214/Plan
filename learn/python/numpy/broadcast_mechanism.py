"""
当两个数组做运算时，NumPy 从最后一维（最右边）开始向前比较，满足以下条件之一即可广播：
    1. 维度大小相等
    2. 其中一个维度大小为 1 
    3. 其中一个数组没有这个维度（维度缺失）

    为1和缺失广播机制都有一个确定的可以复制的样本如果是大于1那就不知道要复制那个去拓展
如果都不满足，就报错
"""

import numpy as np

# 示例1：标量与数组
a = np.array([1, 2, 3])
print(a + 10)          # [11 12 13]

# 示例2：一维数组与二维数组
b = np.array([[1, 2, 3],
              [4, 5, 6]])    # 形状 (2, 3)
c = np.array([10, 20, 30])   # 形状 (3,)
print(b + c)
# [[11 22 33]
#  [14 25 36]]

# 示例3：列向量与行向量
x = np.array([[1], [2], [3]])  # 形状 (3, 1)
y = np.array([10, 20, 30, 40]) # 形状 (4,)
print(x + y)
# [[11 21 31 41]
#  [12 22 32 42]
#  [13 23 33 43]]

# 示例4：形状 (3,1,4) 和 (2,4) 能不能广播？
a = np.random.rand(3, 1, 4)
b = np.random.rand(2, 4)
# 按照规则：从右对齐
# (3, 1, 4)
#    (2, 4)
# 4 和 4 OK；1 和 2 有一个1 OK；3 缺失 OK
# 结果 shape: (3, 2, 4)
print((a + b).shape)  # (3, 2, 4)